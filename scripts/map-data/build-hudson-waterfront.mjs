import fs from "node:fs/promises";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const ROOT = process.cwd();
const OUTPUT = path.join(ROOT, "src/generated/hudson-waterfront.ts");
const ORIGIN = { longitude: -73.99733, latitude: 40.73082 };
const METERS_PER_LATITUDE_DEGREE = 111_320;
const METERS_PER_LONGITUDE_DEGREE = METERS_PER_LATITUDE_DEGREE * Math.cos(ORIGIN.latitude * Math.PI / 180);
const query = `[out:json][timeout:60];(
  way["natural"="coastline"](40.715,-74.025,40.755,-73.955);
  way["man_made"="pier"](40.715,-74.002,40.755,-73.955);
  way["highway"]["name"~"FDR|Franklin D. Roosevelt",i](40.711,-74.005,40.755,-73.955);
  rel(3357426); way(r);
  way(23529474);
  way(379634631);
);out tags geom;`;

const { stdout } = await promisify(execFile)("curl", [
  "-sS",
  "--get",
  "https://overpass-api.de/api/interpreter",
  "--data-urlencode",
  `data=${query}`,
], { maxBuffer: 32 * 1024 * 1024 });
const source = JSON.parse(stdout);

const toLocal = ({ lat, lon }) => [
  Math.round((lon - ORIGIN.longitude) * METERS_PER_LONGITUDE_DEGREE * 1000) / 1000,
  Math.round(-(lat - ORIGIN.latitude) * METERS_PER_LATITUDE_DEGREE * 1000) / 1000,
];
const byId = new Map(source.elements.map((element) => [element.id, element]));
const shoreline = source.elements
  .filter((element) => element.tags?.natural === "coastline" && !element.tags?.name)
  .flatMap((element) => element.geometry ?? [])
  .filter(({ lat, lon }) => lat >= 40.719 && lat <= 40.751 && lon >= -74.015 && lon <= -74.0)
  .sort((a, b) => b.lat - a.lat)
  .filter((point, index, points) => index === 0 || Math.hypot(
    (point.lon - points[index - 1].lon) * METERS_PER_LONGITUDE_DEGREE,
    (point.lat - points[index - 1].lat) * METERS_PER_LATITUDE_DEGREE,
  ) > 1)
  .map(toLocal);
const eastShorelineWayIds = new Set([179060559, 1188974539, 179055615]);
const eastShoreline = source.elements
  .filter((element) => eastShorelineWayIds.has(element.id))
  .flatMap((element) => element.geometry ?? [])
  .filter(({ lat }) => lat >= 40.719 && lat <= 40.751)
  .sort((a, b) => b.lat - a.lat)
  .filter((point, index, points) => index === 0 || Math.hypot(
    (point.lon - points[index - 1].lon) * METERS_PER_LONGITUDE_DEGREE,
    (point.lat - points[index - 1].lat) * METERS_PER_LATITUDE_DEGREE,
  ) > 1)
  .map(toLocal);
const eastPierWayIds = new Set([576263293, 576263294, 576263295, 641683716, 641683717, 718432362]);
const eastPiers = source.elements
  .filter((element) => eastPierWayIds.has(element.id) && element.geometry?.length >= 2)
  .map((element) => ({
    sourceId: element.id,
    area: element.tags?.area === "yes" || (
      element.geometry.length > 3
      && element.geometry[0].lat === element.geometry.at(-1).lat
      && element.geometry[0].lon === element.geometry.at(-1).lon
    ),
    points: element.geometry.map(toLocal),
  }));
const fdrWays = source.elements
  .filter((element) => (
    element.tags?.highway === "motorway" || element.tags?.highway === "primary"
  ) && /FDR|Franklin D\. Roosevelt/i.test(element.tags?.name ?? "") && element.geometry?.length >= 2)
  .map((element) => ({ sourceId: element.id, points: element.geometry.map(toLocal) }));

const geometry = (id) => {
  const element = byId.get(id);
  if (!element?.geometry) throw new Error(`Missing OSM way ${id}`);
  return element.geometry.map(toLocal);
};
const payload = {
  source: "OpenStreetMap coastline and Pier 40 geometry",
  sourceUrl: "https://www.openstreetmap.org/copyright",
  generatedAt: new Date().toISOString(),
  shoreline,
  pier40: {
    outer: geometry(249664809),
    inner: geometry(249664810),
    field: geometry(23529474),
  },
  pier46Lawn: geometry(379634631),
  eastRiver: { shoreline: eastShoreline, piers: eastPiers, fdrWays },
};

await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
await fs.writeFile(OUTPUT, `// Generated by scripts/map-data/build-hudson-waterfront.mjs.\nexport const HUDSON_WATERFRONT = ${JSON.stringify(payload)} as const;\n`);
console.log(`Wrote ${OUTPUT} with ${shoreline.length} Hudson and ${eastShoreline.length} East River shoreline points.`);
